class ProductModel {

  final String id;
  final String image;
  final String productName;
  final String category;
  final String seller;
  final String store;
  final String email;
  final String phone;

  final String price;
  final int stock;
  final int orders;
  final String sales;

  final String description;

  final bool active;

  final String createdDate;


  ProductModel({

    required this.id,
    required this.image,
    required this.productName,
    required this.category,
    required this.seller,
    required this.store,
    required this.email,
    required this.phone,
    required this.price,
    required this.stock,
    required this.orders,
    required this.sales,
    required this.description,
    required this.active,
    required this.createdDate,

  });


}



